/** The shape every language follows: the same keys, any wording. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : { [K in keyof T]: Widen<T[K]> };
export type Strings = Widen<typeof t>;
